export interface ColumnDef {
  name: string;
  type: string;
  nullable: boolean;
  primaryKey: boolean;
  identity: boolean;
  default?: string;
}

export interface ForeignKeyDef {
  name?: string;
  columns: string[];
  refTable: TableRef;
  refColumns: string[];
  onDelete?: string;
  onUpdate?: string;
}

export interface TableDef {
  table: TableRef;
  columns: ColumnDef[];
  foreignKeys: ForeignKeyDef[];
}

function identityClause(kind: DbKind): string {
  switch (kind) {
    case 'postgres':
      return 'GENERATED BY DEFAULT AS IDENTITY';
    case 'mysql':
      return 'AUTO_INCREMENT';
    case 'mssql':
      return 'IDENTITY(1,1)';
    default:
      return '';
  }
}

export function columnSql(kind: DbKind, c: ColumnDef, inlinePk = false): string {
  const parts = [quoteIdent(kind, c.name), c.type];
  if (kind === 'sqlite' && inlinePk) {
    parts.push('PRIMARY KEY');
    if (c.identity) parts.push('AUTOINCREMENT');
  } else if (c.identity) {
    parts.push(identityClause(kind));
  }
  if (!c.nullable && !inlinePk) parts.push('NOT NULL');
  if (c.default !== undefined && c.default !== '') parts.push('DEFAULT ' + c.default);
  return parts.filter(Boolean).join(' ');
}

function fkActions(fk: { onDelete?: string; onUpdate?: string }): string {
  let s = '';
  if (fk.onDelete && fk.onDelete.toUpperCase() !== 'NO ACTION') s += ` ON DELETE ${fk.onDelete.toUpperCase()}`;
  if (fk.onUpdate && fk.onUpdate.toUpperCase() !== 'NO ACTION') s += ` ON UPDATE ${fk.onUpdate.toUpperCase()}`;
  return s;
}

export function createTableSql(kind: DbKind, def: TableDef): string {
  const q = (s: string) => quoteIdent(kind, s);
  const pk = def.columns.filter((c) => c.primaryKey);
  const sqliteInlinePk = kind === 'sqlite' && pk.length === 1 && /^integer$/i.test(pk[0].type.trim());
  const lines = def.columns.map((c) => '  ' + columnSql(kind, c, sqliteInlinePk && c.primaryKey));
  if (pk.length && !sqliteInlinePk) {
    lines.push(`  CONSTRAINT ${q('pk_' + def.table.name)} PRIMARY KEY (${pk.map((c) => q(c.name)).join(', ')})`);
  }
  for (const fk of def.foreignKeys) {
    if (!fk.columns.length || !fk.refTable.name) continue;
    const name = fk.name || `fk_${def.table.name}_${fk.refTable.name}`;
    lines.push(
      `  CONSTRAINT ${q(name)} FOREIGN KEY (${fk.columns.map(q).join(', ')}) REFERENCES ${qualify(kind, fk.refTable)} (${fk.refColumns.map(q).join(', ')})${fkActions(fk)}`,
    );
  }
  return `CREATE TABLE ${qualify(kind, def.table)} (\n${lines.join(',\n')}\n);`;
}

/** Re-create a CREATE TABLE statement from introspected metadata. */
export function tableInfoToDdl(kind: DbKind, t: TableInfo): string {
  const def: TableDef = {
    table: { schema: t.schema, name: t.name },
    columns: t.columns.map((c) => ({
      name: c.name,
      type: c.type,
      nullable: c.nullable,
      primaryKey: c.isPrimaryKey,
      identity: c.isIdentity,
      default: c.isIdentity ? undefined : (c.default ?? undefined),
    })),
    foreignKeys: t.foreignKeys.map((f) => ({
      name: f.name,
      columns: f.columns,
      refTable: { schema: f.refSchema, name: f.refTable },
      refColumns: f.refColumns,
      onDelete: f.onDelete,
      onUpdate: f.onUpdate,
    })),
  };
  let sql = createTableSql(kind, def);
  for (const ix of t.indexes) {
    if (ix.primary) continue;
    sql += '\n\n' + createIndexSql(kind, { schema: t.schema, name: t.name }, ix.name, ix.columns, ix.unique);
  }
  return sql;
}

export function addColumnSql(kind: DbKind, t: TableRef, c: ColumnDef): string {
  const add = kind === 'mssql' ? 'ADD' : 'ADD COLUMN';
  return `ALTER TABLE ${qualify(kind, t)} ${add} ${columnSql(kind, { ...c, primaryKey: false })};`;
}

export function dropColumnSql(kind: DbKind, t: TableRef, col: string): string {
  return `ALTER TABLE ${qualify(kind, t)} DROP COLUMN ${quoteIdent(kind, col)};`;
}

export function renameColumnSql(kind: DbKind, t: TableRef, from: string, to: string): string {
  if (kind === 'mssql') {
    return `EXEC sp_rename ${quoteString(`${t.schema ?? 'dbo'}.${t.name}.${from}`)}, ${quoteString(to)}, 'COLUMN';`;
  }
  return `ALTER TABLE ${qualify(kind, t)} RENAME COLUMN ${quoteIdent(kind, from)} TO ${quoteIdent(kind, to)};`;
}

export function alterColumnTypeSql(kind: DbKind, t: TableRef, c: ColumnDef): string | null {
  const tbl = qualify(kind, t);
  const col = quoteIdent(kind, c.name);
  switch (kind) {
    case 'postgres':
      return [
        `ALTER TABLE ${tbl} ALTER COLUMN ${col} TYPE ${c.type};`,
        `ALTER TABLE ${tbl} ALTER COLUMN ${col} ${c.nullable ? 'DROP' : 'SET'} NOT NULL;`,
      ].join('\n');
    case 'mysql':
      return `ALTER TABLE ${tbl} MODIFY COLUMN ${columnSql(kind, { ...c, primaryKey: false })};`;
    case 'mssql':
      return `ALTER TABLE ${tbl} ALTER COLUMN ${col} ${c.type} ${c.nullable ? 'NULL' : 'NOT NULL'};`;
    default:
      return null; // SQLite cannot alter column types in place
  }
}

export function renameTableSql(kind: DbKind, t: TableRef, to: string): string {
  switch (kind) {
    case 'mssql':
      return `EXEC sp_rename ${quoteString(`${t.schema ?? 'dbo'}.${t.name}`)}, ${quoteString(to)};`;
    case 'mysql':
      return `RENAME TABLE ${qualify(kind, t)} TO ${quoteIdent(kind, to)};`;
    default:
      return `ALTER TABLE ${qualify(kind, t)} RENAME TO ${quoteIdent(kind, to)};`;
  }
}

export function dropTableSql(kind: DbKind, t: TableRef, view = false): string {
  return `DROP ${view ? 'VIEW' : 'TABLE'} ${qualify(kind, t)};`;
}

export function truncateTableSql(kind: DbKind, t: TableRef): string {
  return kind === 'sqlite' ? `DELETE FROM ${qualify(kind, t)};` : `TRUNCATE TABLE ${qualify(kind, t)};`;
}

export function createIndexSql(kind: DbKind, t: TableRef, name: string, cols: string[], unique: boolean): string {
  const q = (s: string) => quoteIdent(kind, s);
  const colList = cols.map((c) => (/[\s()]/.test(c) ? c : q(c))).join(', ');
  // In SQLite and PostgreSQL the index lives in the table's schema; the name itself stays unqualified.
  const ixName = kind === 'sqlite' && t.schema ? `${q(t.schema)}.${q(name)}` : q(name);
  const tbl = kind === 'sqlite' ? q(t.name) : qualify(kind, t);
  return `CREATE ${unique ? 'UNIQUE ' : ''}INDEX ${ixName} ON ${tbl} (${colList});`;
}

export function dropIndexSql(kind: DbKind, t: TableRef, name: string): string {
  switch (kind) {
    case 'mysql':
    case 'mssql':
      return `DROP INDEX ${quoteIdent(kind, name)} ON ${qualify(kind, t)};`;
    default:
      return `DROP INDEX ${t.schema ? quoteIdent(kind, t.schema) + '.' : ''}${quoteIdent(kind, name)};`;
  }
}

export function addForeignKeySql(kind: DbKind, t: TableRef, fk: ForeignKeyDef): string | null {
  if (kind === 'sqlite') return null;
  const q = (s: string) => quoteIdent(kind, s);
  const name = fk.name || `fk_${t.name}_${fk.refTable.name}`;
  return `ALTER TABLE ${qualify(kind, t)} ADD CONSTRAINT ${q(name)} FOREIGN KEY (${fk.columns.map(q).join(', ')}) REFERENCES ${qualify(kind, fk.refTable)} (${fk.refColumns.map(q).join(', ')})${fkActions(fk)};`;
}

export function dropForeignKeySql(kind: DbKind, t: TableRef, name: string): string | null {
  if (kind === 'sqlite') return null;
  const kw = kind === 'mysql' ? 'FOREIGN KEY' : 'CONSTRAINT';
  return `ALTER TABLE ${qualify(kind, t)} DROP ${kw} ${quoteIdent(kind, name)};`;
}

export function selectSql(kind: DbKind, t: TableRef, limit = 100): string {
  return kind === 'mssql'
    ? `SELECT TOP ${limit} *\nFROM ${qualify(kind, t)};`
    : `SELECT *\nFROM ${qualify(kind, t)}\nLIMIT ${limit};`;
}

export function insertTemplateSql(kind: DbKind, t: TableInfo): string {
  const cols = t.columns.filter((c) => !c.isIdentity);
  return `INSERT INTO ${qualify(kind, t)} (${cols.map((c) => quoteIdent(kind, c.name)).join(', ')})\nVALUES (${cols
    .map((c) => `/* ${c.name} ${c.type} */ NULL`)
    .join(', ')});`;
}

export function updateTemplateSql(kind: DbKind, t: TableInfo): string {
  const pk = t.primaryKey.length ? t.primaryKey : [t.columns[0]?.name ?? 'id'];
  const set = t.columns
    .filter((c) => !c.isPrimaryKey && !c.isIdentity)
    .map((c) => `  ${quoteIdent(kind, c.name)} = NULL`)
    .join(',\n');
  return `UPDATE ${qualify(kind, t)}\nSET\n${set}\nWHERE ${pk.map((c) => `${quoteIdent(kind, c)} = NULL`).join(' AND ')};`;
}

export function joinSql(kind: DbKind, t: TableInfo, all: TableInfo[]): string {
  const q = (s: string) => quoteIdent(kind, s);
  const alias = (i: number) => 't' + i;
  const lines = [kind === 'mssql' ? 'SELECT TOP 100 *' : 'SELECT *', `FROM ${qualify(kind, t)} ${alias(0)}`];
  t.foreignKeys.forEach((fk, i) => {
    const ref = all.find((x) => x.name === fk.refTable && (fk.refSchema ? x.schema === fk.refSchema : true));
    const on = fk.columns.map((c, j) => `${alias(i + 1)}.${q(fk.refColumns[j])} = ${alias(0)}.${q(c)}`).join(' AND ');
    lines.push(`LEFT JOIN ${qualify(kind, ref ?? { schema: fk.refSchema, name: fk.refTable })} ${alias(i + 1)} ON ${on}`);
  });
  return lines.join('\n') + (kind === 'mssql' ? ';' : '\nLIMIT 100;');
}

// ---------------- Security (users, roles, grants) ----------------

export const TABLE_PRIVILEGES = ['SELECT', 'INSERT', 'UPDATE', 'DELETE'] as const;

/** Rejects empty or trivial passwords before any SQL is generated. */
export function passwordProblem(pw: string): string | null {
  if (pw.length < 8) return 'Use at least 8 characters';
  if (/^(.)\1*$/.test(pw) || /^(password|12345678|qwertyui)/i.test(pw)) return 'This password is too easy to guess';
  return null;
}

/** MySQL accounts are user@host; other engines use the name alone. */
function account(kind: DbKind, name: string, host?: string | null) {
  return kind === 'mysql' ? `${quoteString(name)}@${quoteString(host || '%')}` : quoteIdent(kind, name);
}

export function createLoginSql(kind: DbKind, name: string, password: string, host?: string): string {
  switch (kind) {
    case 'postgres':
      return `CREATE ROLE ${quoteIdent(kind, name)} LOGIN PASSWORD ${quoteString(password)};`;
    case 'mysql':
      return `CREATE USER ${account(kind, name, host)} IDENTIFIED BY ${quoteString(password)};`;
    case 'mssql':
      return `CREATE LOGIN ${quoteIdent(kind, name)} WITH PASSWORD = N${quoteString(password)};\nCREATE USER ${quoteIdent(kind, name)} FOR LOGIN ${quoteIdent(kind, name)};`;
    default:
      throw new Error('Not supported');
  }
}

export function createRoleSql(kind: DbKind, name: string): string {
  return kind === 'mysql' ? `CREATE ROLE ${quoteString(name)};` : `CREATE ROLE ${quoteIdent(kind, name)};`;
}

export function dropPrincipalSql(kind: DbKind, p: { name: string; kind: string; host?: string | null }): string {
  switch (kind) {
    case 'postgres':
      return `DROP ROLE ${quoteIdent(kind, p.name)};`;
    case 'mysql':
      return p.kind === 'role' ? `DROP ROLE ${account(kind, p.name, p.host)};` : `DROP USER ${account(kind, p.name, p.host)};`;
    case 'mssql':
      if (p.kind === 'role') return `DROP ROLE ${quoteIdent(kind, p.name)};`;
      if (p.kind === 'login') return `DROP LOGIN ${quoteIdent(kind, p.name)};`;
      return `DROP USER ${quoteIdent(kind, p.name)};`;
    default:
      throw new Error('Not supported');
  }
}

export function grantSql(kind: DbKind, privileges: string[], table: TableRef, database: string, grantee: { name: string; host?: string | null }, revoke = false): string {
  const obj = kind === 'mysql' ? `${quoteIdent(kind, database)}.${quoteIdent(kind, table.name)}` : qualify(kind, table);
  const who = account(kind, grantee.name, grantee.host);
  return revoke ? `REVOKE ${privileges.join(', ')} ON ${obj} FROM ${who};` : `GRANT ${privileges.join(', ')} ON ${obj} TO ${who};`;
}

export function addRoleMemberSql(kind: DbKind, role: string, member: { name: string; host?: string | null }, remove = false): string {
  switch (kind) {
    case 'postgres':
      return remove ? `REVOKE ${quoteIdent(kind, role)} FROM ${quoteIdent(kind, member.name)};` : `GRANT ${quoteIdent(kind, role)} TO ${quoteIdent(kind, member.name)};`;
    case 'mysql':
      return remove ? `REVOKE ${quoteString(role)} FROM ${account(kind, member.name, member.host)};` : `GRANT ${quoteString(role)} TO ${account(kind, member.name, member.host)};`;
    case 'mssql':
      return `ALTER ROLE ${quoteIdent(kind, role)} ${remove ? 'DROP' : 'ADD'} MEMBER ${quoteIdent(kind, member.name)};`;
    default:
      throw new Error('Not supported');
  }
}

// ---------------- SQL Server native backup ----------------

export function mssqlBackupSql(database: string, file: string): string {
  return `BACKUP DATABASE ${quoteIdent('mssql', database)}\nTO DISK = N${quoteString(file)}\nWITH COPY_ONLY, INIT, CHECKSUM, STATS = 10;`;
}

export function mssqlRestoreSql(database: string, file: string): string {
  const db = quoteIdent('mssql', database);
  return [
    `-- Disconnects every other session of ${database}, then replaces it with the backup.`,
    `ALTER DATABASE ${db} SET SINGLE_USER WITH ROLLBACK IMMEDIATE;`,
    `RESTORE DATABASE ${db} FROM DISK = N${quoteString(file)} WITH REPLACE, RECOVERY, STATS = 10;`,
    `ALTER DATABASE ${db} SET MULTI_USER;`,
  ].join('\n');
}

// ---------------------------------------------------------------- databases

const COLLATION = /^[A-Za-z0-9_]+$/;

/** CREATE DATABASE for server engines. Names are validated by databaseNameProblem and quoted; options are allow-listed. */
export function createDatabaseSql(kind: DbKind, name: string, opts: { collation?: string; encoding?: string; charset?: string } = {}): string {
  const db = quoteIdent(kind, name.trim());
  const collation = opts.collation && COLLATION.test(opts.collation) ? opts.collation : '';
  switch (kind) {
    case 'mssql':
      return `CREATE DATABASE ${db}${collation ? ` COLLATE ${collation}` : ''};`;
    case 'postgres': {
      const enc = opts.encoding && COLLATION.test(opts.encoding) ? opts.encoding : 'UTF8';
      return `CREATE DATABASE ${db} WITH ENCODING ${quoteString(enc)} TEMPLATE template0;`;
    }
    case 'mysql': {
      const cs = opts.charset && COLLATION.test(opts.charset) ? opts.charset : 'utf8mb4';
      return `CREATE DATABASE ${db} CHARACTER SET ${cs}${collation ? ` COLLATE ${collation}` : ''};`;
    }
    default:
      throw new Error('SQLite databases are files — create one with “Local file”.');
  }
}
