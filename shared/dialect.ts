import type { DbKind, TableInfo, TableRef } from './types.ts';

export function quoteIdent(kind: DbKind, id: string): string {
  switch (kind) {
    case 'mysql':
      return '`' + id.replace(/`/g, '``') + '`';
    case 'mssql':
      return '[' + id.replace(/]/g, ']]') + ']';
    default:
      return '"' + id.replace(/"/g, '""') + '"';
  }
}

export function qualify(kind: DbKind, t: TableRef): string {
  return t.schema ? `${quoteIdent(kind, t.schema)}.${quoteIdent(kind, t.name)}` : quoteIdent(kind, t.name);
}

export function quoteString(s: string): string {
  return "'" + s.replace(/'/g, "''") + "'";
}

export function sqlLiteral(kind: DbKind, v: unknown): string {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number' || typeof v === 'bigint') return String(v);
  if (typeof v === 'boolean') return kind === 'postgres' ? (v ? 'TRUE' : 'FALSE') : v ? '1' : '0';
  const s = String(v);
  return kind === 'mssql' && /[^\x00-\x7f]/.test(s) ? 'N' + quoteString(s) : quoteString(s);
}

